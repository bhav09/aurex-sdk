#!/usr/bin/env python3
"""
Aurex Model Pricing Auto-Sync Scheduler

Fetches the latest LLM pricing data from the LiteLLM community-maintained
pricing catalog (https://github.com/BerriAI/litellm) and writes a clean
JSON file that the backend pricing engine loads at startup.

Run weekly via cron or manually:
    python scripts/sync_pricing.py

The output is written to: backend/data/model_pricing.json
"""

import json
import os
import ssl
import sys
import urllib.request
import urllib.error
from datetime import datetime, timezone
from pathlib import Path

LITELLM_URL = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
OUTPUT_PATH = Path(__file__).parent.parent / "backend" / "data" / "model_pricing.json"


def fetch_litellm_catalog() -> dict:
    """Download the full LiteLLM pricing catalog."""
    print(f"📡 Fetching LiteLLM pricing catalog from:\n   {LITELLM_URL}")
    req = urllib.request.Request(LITELLM_URL, headers={"User-Agent": "AurexPricingSync/1.0"})
    # Try with default SSL first, fall back to unverified for local dev (macOS certifi issue)
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            raw = resp.read().decode("utf-8")
    except urllib.error.URLError:
        ctx = ssl.create_default_context()
        ctx.check_hostname = False
        ctx.verify_mode = ssl.CERT_NONE
        with urllib.request.urlopen(req, timeout=30, context=ctx) as resp:
            raw = resp.read().decode("utf-8")
    return json.loads(raw)


def transform_catalog(raw_catalog: dict) -> dict:
    """
    Filter to chat/completion models and transform to Aurex internal format.
    
    Output schema per model:
    {
      "input_price_per_1m": float,
      "output_price_per_1m": float,
      "cached_input_price_per_1m": float | null,
      "provider": str,
      "context_window": int,
      "max_output_tokens": int | null
    }
    """
    models = {}
    skipped = 0

    for model_key, info in raw_catalog.items():
        # Skip the spec entry and non-chat models
        if model_key == "sample_spec":
            continue

        mode = info.get("mode", "")
        if mode not in ("chat", "completion", ""):
            skipped += 1
            continue

        # Must have token pricing
        input_cost = info.get("input_cost_per_token")
        output_cost = info.get("output_cost_per_token")
        if input_cost is None and output_cost is None:
            skipped += 1
            continue

        input_per_1m = round((input_cost or 0) * 1_000_000, 6)
        output_per_1m = round((output_cost or 0) * 1_000_000, 6)

        # Cache pricing (if available)
        cache_read_cost = info.get("cache_read_input_token_cost")
        cached_per_1m = round(cache_read_cost * 1_000_000, 6) if cache_read_cost else None

        provider = info.get("litellm_provider", "unknown")
        # Normalize provider names
        if "bedrock" in provider:
            provider = "aws_bedrock"
        elif "vertex" in provider:
            provider = "google_vertex"

        context_window = info.get("max_input_tokens") or info.get("max_tokens") or 0
        max_output = info.get("max_output_tokens")

        # Normalize model key: strip regional prefixes like "us.", "eu.", "apac."
        clean_key = model_key
        for prefix in ("us.", "eu.", "apac."):
            if clean_key.startswith(prefix):
                clean_key = clean_key[len(prefix):]
                break

        # Only keep the first (canonical) entry per clean key
        if clean_key in models:
            continue

        models[clean_key] = {
            "input_price_per_1m": input_per_1m,
            "output_price_per_1m": output_per_1m,
            "cached_input_price_per_1m": cached_per_1m,
            "provider": provider,
            "context_window": context_window,
            "max_output_tokens": max_output,
        }

    return models


def main():
    try:
        raw_catalog = fetch_litellm_catalog()
    except (urllib.error.URLError, Exception) as e:
        print(f"❌ Failed to fetch LiteLLM catalog: {e}", file=sys.stderr)
        sys.exit(1)

    models = transform_catalog(raw_catalog)

    # Build final output with metadata
    output = {
        "_metadata": {
            "source": LITELLM_URL,
            "synced_at": datetime.now(timezone.utc).isoformat(),
            "model_count": len(models),
            "note": "Auto-generated by scripts/sync_pricing.py. Do not edit manually.",
        },
        "models": models,
    }

    # Ensure output directory exists
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)

    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(output, f, indent=2)

    print(f"✅ Synced {len(models)} models to {OUTPUT_PATH}")
    print(f"   Timestamp: {output['_metadata']['synced_at']}")

    # Show a few examples
    sample_keys = ["gpt-4o", "claude-3-5-sonnet-20241022", "gemini-2.0-flash", "gpt-4o-mini"]
    print("\n📊 Sample pricing (per 1M tokens):")
    for k in sample_keys:
        m = models.get(k)
        if m:
            cache_str = f", cached=${m['cached_input_price_per_1m']:.2f}" if m.get("cached_input_price_per_1m") else ""
            print(f"   {k}: in=${m['input_price_per_1m']:.2f}, out=${m['output_price_per_1m']:.2f}{cache_str}")


if __name__ == "__main__":
    main()
